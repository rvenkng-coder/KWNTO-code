/// <reference path="../pb_data/types.d.ts" />
// Teams (design section 5, ERD): a team with one owner, its members, and its settings
// (the join code). Creating a team also creates the owner's membership row and the
// settings row (pb_hooks/teams.pb.js). Never edit this file after it has run.
//
// "Is the caller a member of this team" uses the back-relation team_members_via_team
// with the any-match operator ?=: true when at least one membership row of the team
// has the caller as its user. A signed-out caller's id is "", which no row holds.

const IS_MEMBER = "@request.auth.id != '' && team_members_via_team.user ?= @request.auth.id"
const IS_MEMBER_OF_TEAM = "@request.auth.id != '' && team.team_members_via_team.user ?= @request.auth.id"
const IS_TEAM_OWNER = "@request.auth.id != '' && team.owner = @request.auth.id"

migrate((app) => {
  const users = app.findCollectionByNameOrId("users")

  const teams = new Collection({
    type: "base",
    name: "teams",
    fields: [
      { name: "name", type: "text", required: true, min: 1, max: 80 },
      // Required and no cascade: an account that owns a team cannot be deleted until the
      // team is (ERD note on deleting users). The owner never changes (update rule).
      { name: "owner", type: "relation", required: true, collectionId: users.id, maxSelect: 1, cascadeDelete: false },
      { name: "created", type: "autodate", onCreate: true },
    ],
    listRule: null,
    viewRule: null,
    // Verified accounts only (router: verified email is required to create teams); the
    // creator is the owner. The owner field may not be changed later.
    createRule: "@request.auth.id != '' && @request.auth.verified = true && @request.body.owner = @request.auth.id",
    updateRule: "owner = @request.auth.id && @request.body.owner:isset = false",
    deleteRule: "owner = @request.auth.id",
  })
  app.save(teams)

  const members = new Collection({
    type: "base",
    name: "team_members",
    fields: [
      { name: "team", type: "relation", required: true, collectionId: teams.id, maxSelect: 1, cascadeDelete: true },
      // Deleting a plain member's account removes their memberships (design 6.8).
      { name: "user", type: "relation", required: true, collectionId: users.id, maxSelect: 1, cascadeDelete: true },
      { name: "role", type: "select", required: true, maxSelect: 1, values: ["owner", "member"] },
      // A copy of users.name kept by pb_hooks/teams.pb.js (decision D6): teammates may not
      // read each other's user records, which hold the private email.
      { name: "user_name", type: "text", max: 255 },
      { name: "created", type: "autodate", onCreate: true },
    ],
    indexes: ["CREATE UNIQUE INDEX idx_team_members_team_user ON team_members (team, user)"],
    listRule: null,
    viewRule: null,
    // Rows are made only by the server: with the team, by join code or by invite.
    createRule: null,
    updateRule: null,
    // Only the owner removes members, and never their own row (D8: the owner stays).
    deleteRule: IS_TEAM_OWNER + " && user != @request.auth.id",
  })
  app.save(members)

  // The member rules can only be set once team_members exists, since they read it.
  teams.listRule = IS_MEMBER
  teams.viewRule = IS_MEMBER
  app.save(teams)
  members.listRule = IS_MEMBER_OF_TEAM
  members.viewRule = IS_MEMBER_OF_TEAM
  app.save(members)

  const settings = new Collection({
    type: "base",
    name: "team_settings",
    fields: [
      { name: "team", type: "relation", required: true, collectionId: teams.id, maxSelect: 1, cascadeDelete: true },
      { name: "join_code", type: "text", required: true, min: 8, max: 8 },
      // Off by default; the owner turns it on (decision D1).
      { name: "join_code_enabled", type: "bool" },
    ],
    indexes: [
      "CREATE UNIQUE INDEX idx_team_settings_team ON team_settings (team)",
      // Joining by code (Task 7) looks a team up by its code, so two teams may not share one.
      "CREATE UNIQUE INDEX idx_team_settings_join_code ON team_settings (join_code)",
    ],
    // Only the owner reads the row: the join code lets anyone who has it join.
    listRule: IS_TEAM_OWNER,
    viewRule: IS_TEAM_OWNER,
    createRule: null,
    // The code itself is generated by the server (regenerated by a Task 7 route).
    updateRule: IS_TEAM_OWNER + " && @request.body.join_code:isset = false && @request.body.team:isset = false",
    deleteRule: null,
  })
  app.save(settings)
}, (app) => {
  for (const name of ["team_settings", "team_members", "teams"]) {
    app.delete(app.findCollectionByNameOrId(name))
  }
})
