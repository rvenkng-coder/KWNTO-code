import { expect, test } from 'vitest'
import { expectNoRows, expectRefused } from './helpers/admin-only.ts'
import { asAnonymous, asUser, createTeam, createUser } from './helpers/pb.ts'
import { addMember, expectCreateRefused, teamRows } from './helpers/teams.ts'

// Protects design section 7c and the ERD ("team_settings: one row per team, editable by
// the team owner") and design 5 ("Only the owner ... regenerates or disables the join
// code"). Members must not read the join code: whoever has it can bring others in.
// Also decision D1 (the code is off by default) and docs/security.md section 2.

async function settingsOf(teamId: string): Promise<Record<string, unknown> & { id: string }> {
  const rows = await teamRows('team_settings', teamId)
  expect(rows).toHaveLength(1)
  return rows[0] as Record<string, unknown> & { id: string }
}

// ERD: the owner edits the team's settings, so they can read them.
test('team_settings: the owner lists and views their team settings', async () => {
  const owner = await createUser()
  const team = await createTeam(owner)
  const row = await settingsOf(team.id)
  const pb = await asUser(owner)

  expect((await pb.collection('team_settings').getFullList()).map((r) => r.id)).toEqual([row.id])
  expect((await pb.collection('team_settings').getOne(row.id)).join_code).toBe(team.joinCode)
})

// Design 5: only the owner manages the join code; a member must not see it.
test('team_settings: a plain member, an outsider and a signed-out visitor get nothing', async () => {
  const [owner, member, outsider] = [await createUser(), await createUser(), await createUser()]
  const team = await createTeam(owner)
  await addMember(team.id, member)
  const row = await settingsOf(team.id)

  for (const pb of [await asUser(member), await asUser(outsider), asAnonymous()]) {
    await expectNoRows(pb, 'team_settings')
    await expect(pb.collection('team_settings').getOne(row.id)).rejects.toMatchObject({ status: 404 })
    await expectRefused(pb.collection('team_settings').update(row.id, { join_code_enabled: true }))
  }
  expect((await settingsOf(team.id)).join_code_enabled).toBe(false)
})

// D1: the code is off by default and the owner turns it on (and off again).
test('team_settings: the owner can turn the join code on and off', async () => {
  const owner = await createUser()
  const team = await createTeam(owner)
  const row = await settingsOf(team.id)
  const pb = await asUser(owner)

  expect((await pb.collection('team_settings').update(row.id, { join_code_enabled: true })).join_code_enabled).toBe(true)
  expect((await settingsOf(team.id)).join_code_enabled).toBe(true)
  expect((await pb.collection('team_settings').update(row.id, { join_code_enabled: false })).join_code_enabled).toBe(false)
})

// The code is generated by the server (Task 7 regenerates it). A chosen code could be
// guessable or copied from another team; a moved row would change another team's code.
test('team_settings: the owner cannot write the join code or the team directly', async () => {
  const owner = await createUser()
  const team = await createTeam(owner)
  const otherTeam = await createTeam(owner)
  const row = await settingsOf(team.id)
  const pb = await asUser(owner)

  await expectRefused(pb.collection('team_settings').update(row.id, { join_code: 'AAAAAAAA' }))
  await expectRefused(pb.collection('team_settings').update(row.id, { team: otherTeam.id }))
  const after = await settingsOf(team.id)
  expect(after.join_code).toBe(team.joinCode)
  expect(after.id).toBe(row.id)
})

// ERD: exactly one row per team, made with the team and removed with it.
test('team_settings: nobody can create or delete a row through the API', async () => {
  const [owner, member] = [await createUser(), await createUser()]
  const team = await createTeam(owner)
  await addMember(team.id, member)
  const row = await settingsOf(team.id)

  for (const pb of [await asUser(owner), await asUser(member)]) {
    await expectCreateRefused(pb.collection('team_settings').create({ team: team.id, join_code: 'BBBBBBBB' }))
    await expectRefused(pb.collection('team_settings').delete(row.id))
  }
  expect((await settingsOf(team.id)).id).toBe(row.id)
})

// Injection strings must be treated as data (docs/security.md section 5).
test('team_settings: an injection string in a filter returns nothing', async () => {
  const someone = await createUser()
  await createTeam(someone)
  const pb = await asUser(someone)
  await expectNoRows(pb, 'team_settings', pb.filter('id = {:n}', { n: `' OR 1=1 --` }))
})
